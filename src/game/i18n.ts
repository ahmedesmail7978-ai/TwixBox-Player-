export type StrKey = keyof typeof dict.ru

let current: Lang = 'ru'

export function detectLang(sdkLang?: string): Lang {
  if (sdkLang === 'ru' || sdkLang === 'en') return sdkLang
  const nav = (typeof navigator !== 'undefined' && navigator.language?.toLowerCase()) || 'ru'
  return nav.startsWith('ru') ? 'ru' : 'en'
}

export function setLang(l: Lang) { current = l }
export function getLang(): Lang { return current }
export function t(key: StrKey): string { return dict[current][key] ?? dict.ru[key] ?? key }

